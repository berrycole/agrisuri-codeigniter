const vm=require('node:vm');
const fs=require('node:fs');
const assert=require('node:assert/strict');
const context=vm.createContext({window:{},localStorage:{getItem:()=>null,setItem:()=>{}},URLSearchParams,location:{search:''},console});
vm.runInContext(fs.readFileSync('public/assets/app.js','utf8'),context);
const run=(type,values={})=>{context.params=new URLSearchParams(values);return vm.runInContext(`act('${type}',params)`,context)};
assert.throws(()=>run('reserve',{batch:'R-001',request:'B-001',qty:600}),/eligible/);
assert.throws(()=>run('inspect',{batch:'R-001',cleared:700,held:100}),/equal/);
assert.throws(()=>run('outcome',{case:'C-001',outcome:'Finished'}),/Approve/);
run('approve',{case:'C-001',action:'Package cleared stock',owner:'Demo officer',due:'2026-11-06',estimate:1200});
run('package',{batch:'R-001',qty:200,cost:1200});
run('reserve',{batch:'R-001',request:'B-001',qty:600});
assert.throws(()=>run('reserve',{batch:'R-001',request:'B-001',qty:1}),/eligible/);
assert.throws(()=>run('delivery',{request:'B-001',sent:600,accepted:550,rejected:0}),/account/);
run('delivery',{request:'B-001',sent:600,accepted:550,rejected:50});
run('outcome',{case:'C-001',outcome:'550 kg accepted. Investigate the returned 50 kg.',actual:1200});
assert.equal(vm.runInContext('d.requests[0].accepted',context),550);
assert.equal(vm.runInContext('d.allocations[0].qty',context),600);
assert.equal(vm.runInContext('d.batches[0].reserved',context),600);
assert.throws(()=>run('package',{batch:'R-001',qty:-10}),/nonnegative/);
console.log('PASS: complete browser simulation and stock / outcome safeguards.');
